# --- 3. SMS OUTGOING QUEUE SERIALIZER TESTS ---

@pytest.mark.django_db
def test_sms_outgoing_queue_serializer(new_sms_outgoing, new_user):
    """Checks interface payloads generated by outbound hardware lanes."""
    user_instance = new_user(username="sms_customer")
    user_instance.save()

    customer_profile = CustomerModel.objects.create(user=user_instance)
    booking = BookingModel.objects.create(customer=customer_profile)

    sms = new_sms_outgoing(booking=booking, phone_number="+2399901234",
                           message_text="Invoice Link",
                           is_sent=True)
    sms.save()

    serializer = SMSOutgoingQueueSerializer(instance=sms)
    data = serializer.data

    assert data["id"] == sms.id
    assert data["phone_number"] == "+2399901234"
    assert data["message_text"] == "Invoice Link"
    assert data["is_sent_by_phone"] is True


# --- 4. REVIEWS & FEEDBACK SERIALIZER TESTS ---

@pytest.mark.django_db
def test_review_serializer(monkeypatch, new_user):
    """Tests review object serialization lifecycle without hardcoded static imports."""
    user_instance = new_user(username="reviewer_alpha")
    user_instance.save()

    customer = CustomerModel.objects.create(user=user_instance)

    mock_service = VendorModel.objects.create(company_name="Reviewed Service")
    vendor_content_type = ContentType.objects.get_for_model(VendorModel)

    monkeypatch.setattr(
        ReviewSerializer,
        "validate_model_type",
        lambda self, value: vendor_content_type
    )

    valid_payload = {
        "content": "Had an incredible experience with this service vendor!",
        "rating": 5,
        "model_type": "vendor",
        "object_id": mock_service.id,
    }

    serializer = ReviewSerializer(data=valid_payload)
    assert serializer.is_valid(), serializer.errors

    review = serializer.save(customer=customer)

    assert review.id is not None
    assert review.customer == customer
    assert review.content == "Had an incredible experience with this service vendor!"
    assert review.rating == 5

    outbound_serializer = ReviewSerializer(instance=review)
    data = outbound_serializer.data

    assert data["customer_username"] == "reviewer_alpha"
    assert data["content"] == "Had an incredible experience with this service vendor!"
