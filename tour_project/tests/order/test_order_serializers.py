BookingModel = apps.get_model("order", "Booking")


# --- 1. CART SERIALIZER TESTS ---

@pytest.mark.django_db
def test_cart_serializer(new_cart, new_cart_item):
    """Tests serialization of a Cart model along with its nested CartItems."""
    cart = new_cart()
    cart.save()

    mock_service = VendorModel.objects.create(company_name="Serializer Service")

    item1 = new_cart_item(cart=cart, content_object=mock_service, days=2)
    item1.save()
    item2 = new_cart_item(cart=cart, content_object=mock_service, days=5)
    item2.save()

    serializer = CartSerializer(instance=cart)
    data = serializer.data

    assert data["id"] == str(cart.id)
    assert "created_at" in data
    assert len(data["items"]) == 2
    assert data["items"][0]["id"] == item1.id
    assert data["items"][0]["days"] == 2
    assert data["items"][1]["days"] == 5


@pytest.mark.django_db
def test_cart_item_serializer_creation():
    """Validates direct instantiation, validation, and popping of model_type tags."""
    mock_service = VendorModel.objects.create(company_name="Transient Item Check")

