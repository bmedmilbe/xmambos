# --- 2. BOOKING SERIALIZER TESTS ---

@pytest.mark.django_db
def test_booking_and_item_serializers(new_booking_item, new_user):
    """Tests the combined nested representation output for Booking\
          & BookingItem models."""
    user_instance = new_user(username="booking_customer_alpha")
    user_instance.save()

    customer_profile = CustomerModel.objects.create(user=user_instance)

    # Instantiate Booking directly to bypass the broken conftest fixture fallback
    booking = BookingModel.objects.create(customer=customer_profile)

    mock_service = VendorModel.objects.create(company_name="Booked Service Target")

    item = new_booking_item(booking=booking, content_object=mock_service, days=3)
    item.save()

    serializer = BookingSerializer(instance=booking)
    data = serializer.data

    assert data["id"] == booking.id
    assert data["customer_username"] == "booking_customer_alpha"
    assert len(data["items"]) == 1
    assert data["items"][0]["days"] == 3


